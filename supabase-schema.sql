-- 1. Profile
CREATE TABLE IF NOT EXISTS public.profile (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL DEFAULT 'Khairi Nugroho',
    hero TEXT DEFAULT 'systems engineer • builder • bay area, ca',
    who_am_i TEXT DEFAULT '',
    what_i_did TEXT DEFAULT '',
    school TEXT DEFAULT '',
    photo TEXT DEFAULT '',
    email TEXT DEFAULT 'khairizakiyn@gmail.com',
    x_url TEXT DEFAULT 'https://instagram.com',
    github_url TEXT DEFAULT 'https://github.com',
    linkedin_url TEXT DEFAULT 'https://linkedin.com',
    spotify_url TEXT DEFAULT 'https://spotify.com',
    resume_url TEXT DEFAULT '#',
    motto TEXT DEFAULT 'Precision is quiet; restraint speaks louder than ornamentation.',
    created_at TIMESTAMPTZ DEFAULT NOW(),
    updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- 2. Bio / Who Am I
CREATE TABLE IF NOT EXISTS public.bio (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    subtitle TEXT NOT NULL DEFAULT 'systems engineer • builder • bay area, ca',
    paragraph_1 TEXT NOT NULL DEFAULT '',
    paragraph_2 TEXT DEFAULT '',
    content TEXT DEFAULT '',
    created_at TIMESTAMPTZ DEFAULT NOW(),
    updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- 3. Experiences
CREATE TABLE IF NOT EXISTS public.experiences (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company TEXT NOT NULL,
    initial TEXT NOT NULL DEFAULT '',
    initial_bg TEXT NOT NULL DEFAULT '#1b1c18',
    role TEXT NOT NULL,
    location TEXT DEFAULT '',
    period TEXT NOT NULL,
    star BOOLEAN DEFAULT false,
    description TEXT NOT NULL DEFAULT '',
    badges JSONB DEFAULT '[]'::jsonb,
    order_index INT DEFAULT 0,
    published BOOLEAN DEFAULT true,
    created_at TIMESTAMPTZ DEFAULT NOW(),
    updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- 4. Projects
CREATE TABLE IF NOT EXISTS public.projects (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title TEXT NOT NULL,
    category TEXT DEFAULT 'SYSTEMS',
    progress INT DEFAULT 5,
    description TEXT DEFAULT '',
    image TEXT DEFAULT '',
    url TEXT DEFAULT '',
    star BOOLEAN DEFAULT false,
    stars_count TEXT DEFAULT '',
    tags JSONB DEFAULT '[]'::jsonb,
    links JSONB DEFAULT '[]'::jsonb,
    published BOOLEAN DEFAULT true,
    created_at TIMESTAMPTZ DEFAULT NOW(),
    updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- 5. Music Albums
CREATE TABLE IF NOT EXISTS public.music (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title TEXT NOT NULL,
    artist TEXT NOT NULL,
    year TEXT NOT NULL,
    genre TEXT DEFAULT '',
    tag TEXT DEFAULT '',
    progress INT DEFAULT 50,
    time TEXT DEFAULT '02:30 / 03:45',
    initial TEXT DEFAULT '',
    gradient TEXT DEFAULT 'linear-gradient(135deg, #1f2937, #111827)',
    note TEXT DEFAULT '',
    row_index INT DEFAULT 1,
    order_index INT DEFAULT 0,
    published BOOLEAN DEFAULT true,
    created_at TIMESTAMPTZ DEFAULT NOW(),
    updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- 6. Tiguan Details & Mods
CREATE TABLE IF NOT EXISTS public.tiguan (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title TEXT NOT NULL DEFAULT '2021 Volkswagen Tiguan R-Line (MQB platform)',
    color TEXT NOT NULL DEFAULT 'Deep Black Pearl',
