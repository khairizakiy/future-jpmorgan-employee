-- Allow public read access to bio
DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_policies WHERE tablename = 'bio' AND policyname = 'Allow public read access on bio'
    ) THEN
        CREATE POLICY "Allow public read access on bio"
        ON public.bio FOR SELECT
        USING (true);
    END IF;
END $$;

-- Allow full access for backend service role & authenticated users
DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_policies WHERE tablename = 'bio' AND policyname = 'Allow all access on bio'
    ) THEN
        CREATE POLICY "Allow all access on bio"
        ON public.bio FOR ALL
        USING (true)
        WITH CHECK (true);
    END IF;
END $$;
